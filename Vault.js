/* --- the seeded generator ----------------------------------------------------- */
/** A seed: a whole number the server keeps. */
const vaultSeed = () => Math.floor(Math.random() * 2147483646) + 1;
/** mulberry32: the same seed, the same safe, on any machine. */
const vaultRng = (seed) => {
  let a = (Number(seed) >>> 0) || 1;
  return () => {
    a = (a + 0x6D2B79F5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
};
const vaultInt = (rnd, n) => Math.floor(rnd() * n);
const vaultPick = (rnd, list) => list[vaultInt(rnd, list.length)];
const vaultShuffleR = (rnd, list) => {
  const out = list.slice();
  for (let i = out.length - 1; i > 0; i--) { const j = vaultInt(rnd, i + 1); const t = out[i]; out[i] = out[j]; out[j] = t; }
  return out;
};

/* --- the notebook (the manual), one per game ------------------------------------
   manual = {
     wires:   { 3: [rule…], 4: […], 5: […], 6: […] }   three rules and «غير كده» each
     symbols: [[ids × 7] × 6]                           the columns
     dial:    { codes: { shape: [d, d, d] }, twist: 'lastOdd' | 'firstEven' | 'sumBig' }
     lights:  [{ r, b, g, y } × 3]                      the map with no mistakes, after one, after two or more
   }
   A wire rule: { if: { t, c } | null, do: { t: 'pos', p } | { t: 'lastOf', c } | { t: 'firstOf', c } }
     if.t  'none' no c wire · 'last' the last wire is c · 'first' the first is c
           'many' more than one c · 'one' exactly one c */
const VAULT_WIRE_IFS = ['none', 'last', 'first', 'many', 'one'];

const vaultWireRules = (rnd, n) => {
  const rules = [];
  const used = {};
  vaultShuffleR(rnd, VAULT_WIRE_IFS).slice(0, 3).forEach((t) => {
    let c = vaultPick(rnd, VAULT_WIRE_COLORS);
    for (let k = 0; k < 6 && used[t + c]; k++) c = vaultPick(rnd, VAULT_WIRE_COLORS);
    used[t + c] = true;
    let act;
    if (t === 'many') act = rnd() < 0.6 ? { t: 'lastOf', c } : { t: 'pos', p: vaultInt(rnd, n) };
    else if (t === 'one') act = rnd() < 0.6 ? { t: 'firstOf', c } : { t: 'pos', p: vaultInt(rnd, n) };
    else if (t === 'last') act = rnd() < 0.5 ? { t: 'pos', p: n - 1 } : { t: 'pos', p: vaultInt(rnd, n - 1) };
    else act = { t: 'pos', p: vaultInt(rnd, n) };
    rules.push({ if: { t, c }, do: act });
  });
  rules.push({ if: null, do: { t: 'pos', p: vaultInt(rnd, n) } });
  return rules;
};

/** A derangement of the four light colours: no colour presses itself. */
const vaultLightRow = (rnd) => {
  for (;;) {
    const to = vaultShuffleR(rnd, VAULT_LIGHT_COLORS);
    if (to.every((c, i) => c !== VAULT_LIGHT_COLORS[i])) {
      const row = {};
      VAULT_LIGHT_COLORS.forEach((c, i) => { row[c] = to[i]; });
      return row;
    }
  }
};

const vaultManual = (seed) => {
  const rnd = vaultRng(seed);
  const wires = {};
  [3, 4, 5, 6].forEach((n) => { wires[n] = vaultWireRules(rnd, n); });
  const symbols = [];
  for (let c = 0; c < VAULT_COLS; c++) symbols.push(vaultShuffleR(rnd, VAULT_SYMBOL_IDS).slice(0, VAULT_COL_LEN));
  const codes = {};
  const taken = {};
  VAULT_SHAPE_IDS.forEach((sh) => {
    let code;
    do { code = [vaultInt(rnd, 10), vaultInt(rnd, 10), vaultInt(rnd, 10)]; } while (taken[code.join('')] || taken[code.slice().reverse().join('')] || code[0] === code[2]);
    taken[code.join('')] = true;
    codes[sh] = code;
  });
  const twist = vaultPick(rnd, ['lastOdd', 'firstEven', 'sumBig']);
  const lights = [];
  while (lights.length < 3) {
    const row = vaultLightRow(rnd);
    if (!lights.some((x) => VAULT_LIGHT_COLORS.every((c) => x[c] === row[c]))) lights.push(row);
  }
  return { wires, symbols, dial: { codes, twist }, lights };
};

/* --- the answers ---------------------------------------------------------------- */
const vaultWireIf = (cond, wires) => {
  if (!cond) return true;
  const n = wires.filter((x) => x === cond.c).length;
  if (cond.t === 'none') return n === 0;
  if (cond.t === 'many') return n > 1;
  if (cond.t === 'one') return n === 1;
  if (cond.t === 'last') return wires[wires.length - 1] === cond.c;
  if (cond.t === 'first') return wires[0] === cond.c;
  return false;
};
const vaultWireDo = (act, wires) => {
  if (act.t === 'lastOf') return wires.lastIndexOf(act.c);
  if (act.t === 'firstOf') return wires.indexOf(act.c);
  return Math.min(wires.length - 1, Math.max(0, act.p));
};
/** The wire to cut: the first rule for that count that applies (index from the top, 0-based). */
const vaultWireAnswer = (rules, wires) => {
  const list = (rules || {})[wires.length] || [];
  for (let k = 0; k < list.length; k++) {
    if (vaultWireIf(list[k].if, wires)) {
      const i = vaultWireDo(list[k].do, wires);
      if (i >= 0) return i;
    }
  }
  return wires.length - 1;
};

/** The one column holding every symbol shown, or -1. */
const vaultSymbolCol = (cols, shown) => {
  const hits = [];
  (cols || []).forEach((col, i) => { if (shown.every((x) => col.indexOf(x) !== -1)) hits.push(i); });
  return hits.length === 1 ? hits[0] : -1;
};
/** The order to press: the symbols shown, as their column lists them from the top. */
const vaultSymbolOrder = (cols, shown) => {
  const c = vaultSymbolCol(cols, shown);
  return c < 0 ? null : cols[c].filter((x) => shown.indexOf(x) !== -1);
};

/** Does the chest's number turn the code backwards? */
const vaultTwistOn = (twist, serial) => {
  const d = String(serial || '').split('').map(Number);
  if (!d.length) return false;
  if (twist === 'lastOdd') return d[d.length - 1] % 2 === 1;
  if (twist === 'firstEven') return d[0] % 2 === 0;
  if (twist === 'sumBig') return d.reduce((a, x) => a + x, 0) >= 20;
  return false;
};
const vaultDialCode = (dial, shape, serial) => {
  const code = ((dial || {}).codes || {})[shape];
  if (!code) return null;
  return vaultTwistOn(dial.twist, serial) ? code.slice().reverse() : code.slice();
};

/** The light rows: no mistakes, one, two or more. */
const vaultLightRowOf = (mistakes) => Math.min(2, Math.max(0, Number(mistakes) || 0));
/** The buttons to press for a flashed pattern, with this many mistakes so far. */
const vaultLightAnswer = (lights, seq, mistakes) => {
  const row = (lights || [])[vaultLightRowOf(mistakes)] || {};
  return seq.map((c) => row[c]);
};

/* --- a safe ---------------------------------------------------------------------
   safe = { seed, serial: '4827', locks: [{ k, look, sol }] }
     wires   look { wires: ['r', …] }        sol: the index to cut
     symbols look { syms: [ids, shuffled] }  sol: the ids in order
     dial    look { shape }                  sol: [d, d, d]
     lights  look { seq: ['r', …] }          sol: null (it depends on the mistakes at the time)
   `kinds` is the locks in the safe, in order; `L` a vaultLevel. */
const vaultMakeSafe = (seed, manual, kinds, L) => {
  const rnd = vaultRng(seed);
  let serial = String(1 + vaultInt(rnd, 9));
  for (let k = 0; k < 3; k++) serial += String(vaultInt(rnd, 10));
  const locks = kinds.map((k) => {
    if (k === 'wires') {
      const n = L.wires[0] + vaultInt(rnd, L.wires[1] - L.wires[0] + 1);
      let wires;
      do { wires = []; for (let i = 0; i < n; i++) wires.push(vaultPick(rnd, VAULT_WIRE_COLORS)); } while (wires.every((x) => x === wires[0]));
      return { k, look: { wires }, sol: vaultWireAnswer(manual.wires, wires) };
    }
    if (k === 'symbols') {
      for (let tries = 0; tries < 200; tries++) {
        const col = manual.symbols[vaultInt(rnd, manual.symbols.length)];
        const shown = vaultShuffleR(rnd, col).slice(0, L.syms);
        const order = vaultSymbolOrder(manual.symbols, shown);
        if (order) return { k, look: { syms: shown }, sol: order };
      }
      // Never in practice (six random columns of seven from 32 hardly share four); a sure one anyway.
      const col = manual.symbols[0].filter((x) => !manual.symbols.slice(1).some((c) => c.indexOf(x) !== -1));
      const shown = (col.length >= L.syms ? col : manual.symbols[0]).slice(0, L.syms);
      return { k, look: { syms: vaultShuffleR(rnd, shown) }, sol: manual.symbols[0].filter((x) => shown.indexOf(x) !== -1) };
    }
    if (k === 'dial') {
      const shape = vaultPick(rnd, VAULT_SHAPE_IDS);
      return { k, look: { shape }, sol: vaultDialCode(manual.dial, shape, serial) };
    }
    const seq = [];
    for (let i = 0; i < L.lights; i++) seq.push(vaultPick(rnd, VAULT_LIGHT_COLORS));
    return { k, look: { seq }, sol: null };
  });
  return { seed, serial, locks };
};

/* --- the notebook's pages ---------------------------------------------------------
   A page is a lock's part of the notebook: 'wires', or a half of it ('wires.1',
   'wires.2') when there are more readers than locks. A half of the wires holds
   3-4 wires or 5-6; of the symbols columns 1-3 or 4-6; of the dial the first
   five shapes or the last four (both with the twist); of the lights red and
   blue or green and yellow. */
const VAULT_HALVES = {
  wires: [[3, 4], [5, 6]],
  symbols: [[0, 1, 2], [3, 4, 5]],
  dial: [VAULT_SHAPE_IDS.slice(0, 5), VAULT_SHAPE_IDS.slice(5)],
  lights: [['r', 'b'], ['g', 'y']]
};
const vaultUnitKind = (u) => String(u || '').split('.')[0];
const vaultUnitPart = (u) => Number(String(u || '').split('.')[1]) || 0;

/** What a page holds, from the manual: what a reader's phone is sent. */
const vaultPageData = (manual, u) => {
  const k = vaultUnitKind(u);
  const part = vaultUnitPart(u);
  const half = part ? VAULT_HALVES[k][part - 1] : null;
  if (k === 'wires') {
    const rules = {};
    (half || [3, 4, 5, 6]).forEach((n) => { rules[n] = manual.wires[n]; });
    return { u, k, part, rules };
  }
  if (k === 'symbols') {
    return { u, k, part, cols: (half || [0, 1, 2, 3, 4, 5]).map((i) => ({ n: i + 1, syms: manual.symbols[i].slice() })) };
  }
  if (k === 'dial') {
    return { u, k, part, codes: (half || VAULT_SHAPE_IDS).map((sh) => ({ s: sh, c: manual.dial.codes[sh].slice() })), twist: manual.dial.twist };
  }
  const colors = half || VAULT_LIGHT_COLORS;
  return { u, k, part, colors: colors.slice(), rows: manual.lights.map((row) => colors.map((c) => row[c])) };
};

/** The pages of a safe for `readers` readers: whole pages, halved one lock at a time while readers outnumber them. */
const vaultUnits = (kinds, readers) => {
  const units = [];
  const uniq = kinds.filter((k, i) => kinds.indexOf(k) === i);
  uniq.forEach((k) => units.push(k));
  for (let i = 0; i < uniq.length && units.length < readers; i++) {
    const at = units.indexOf(uniq[i]);
    units.splice(at, 1, uniq[i] + '.1', uniq[i] + '.2');
  }
  return units;
};
/** Pages shared out to readers: contiguous groups while there are enough pages, else copies round. */
const vaultDealUnits = (units, readers) => {
  const out = readers.map(() => []);
  if (!readers.length) return out;
  if (units.length >= readers.length) {
    const base = Math.floor(units.length / readers.length);
    const extra = units.length % readers.length;
    let at = 0;
    readers.forEach((r, i) => { const n = base + (i < extra ? 1 : 0); out[i] = units.slice(at, at + n); at += n; });
  } else {
    readers.forEach((r, i) => { out[i] = [units[i % units.length]]; });
  }
  return out;
};
