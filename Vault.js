/**
 * A level: how many locks, how hard each, and the time. Endless levels count
 * up one a safe; a set of safes plays safe k at level k.
 *   locks   2 at level 1, 3 at level 2, all 4 from level 3 («الكل»: one per phone)
 *   wires   3-4 wires, then 3-5 from level 3, 4-6 from level 5
 *   syms    4 symbols, 5 from level 5
 *   lights  a pattern of 3, 4 from level 3, 5 from level 5
 *   ms      the candle: 2:30, 3:00, 3:30, then 15 s less a level, never under 2:00;
 *           «الكل» (every lock at once): 2:30, 10 s less a level, never under 1:15
 */
const vaultLevel = (level, way) => {
  const L = Math.max(1, Number(level) || 1);
  return {
    locks: L <= 1 ? 2 : L === 2 ? 3 : 4,
    wires: L <= 2 ? [3, 4] : L <= 4 ? [3, 5] : [4, 6],
    syms: L >= 5 ? 5 : 4,
    lights: L <= 2 ? 3 : L <= 4 ? 4 : 5,
    ms: way === 'all'
      ? Math.max(75000, 150000 - 10000 * (L - 1))
      : (L <= 1 ? 150000 : L === 2 ? 180000 : Math.max(120000, 210000 - 15000 * (L - 3)))
  };
};

